            add_comment_meta( $comment_id, 'rating', (int) esc_attr( $_COOKIE['RstarRating'] ), true );
        }
        $url = get_the_permalink( $_COOKIE['RproductID'] );
        setcookie ('review_redirect', urldecode($url), time()+30, '/');
    }
    //TODO DELETE COOKIES ALSO ON PRODUCT PAGE LOAD?
    //unset($_COOKIE['mycookiename']);
    setcookie ('RproductID', '', time() - 3600);
