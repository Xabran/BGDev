// carousel creator
function _brgm_carousel( $ids, $arg = null, $type = '' ) {
    if ( !$ids && !$arg ) return false;
    
    $args = ( $arg ) ? $arg : array(
        'post_type'     => 'product',
        'post_per_page' => 20,
        'post__in'      => $ids,
    );
