function brgm_get_bucks_earned($items){
    if( is_plugin_active( 'bgpr/bgpr.php' ) ) {
        global $wpdb;
    
        $order_items = $items;
        $total_valid_items = 0;
        $total_earned = 0;
        foreach ($order_items as $anItem) {
