    $liClassAdd = '';
    if($type === 'formatted'){
        $ulClassAdd = ' products imgfix';
        $liClassAdd = ' product';
    }
    
    $query = new WP_QUery( $args ); 
    $posts = $query->get_posts(); 

    $item = '<ul class="bg-item-list carousel carousel-hide'.$ulClassAdd.'">';
    foreach ( $posts as $post ) {
        $prod = wc_get_product( $post->ID );
        
