            .'" data-quantity="1" data-product_id="'.$prod->id
            .'" data-product_sku="'.$prod->get_sku().'" class="button product_type_simple add_to_cart_button ajax_add_to_cart">'
            .$prod->add_to_cart_text().'</a>';
        }else{
            $cart = do_shortcode('[add_to_cart style="padding: 3px !important;" show_price="false" id='.$post->ID.']');
        }
        
        $price = ( !$prod->is_on_sale() ) ? '<span class="regular-price">$'
                .$prod->get_price().'</span>':
             '<span class="sale-price">$'.$prod->get_regular_price().'</span>'.
             '<span class="regular-price">$'.$prod->get_price().'</span>';
        if ( !$prod->get_price() ) $price = '';
        $imageDims = array(200,200);
        if ( $type === 'image' ) {//class was item product carousel_override
            $item .= '<li class="item'.$liClassAdd.'" '.$formattedStyle.'><a href="'.get_the_permalink( $post->ID ).'">'
                    .wp_get_attachment_image( 
                        get_post_thumbnail_id( $post->ID ), $imageDims ).'</li>';
                        //.$post->get_image().'</li>';
        } else {
            $item .= '<li class="item'.$liClassAdd.'" '.$formattedStyle.'><a href="'.get_the_permalink( $post->ID ).'">'
                    .wp_get_attachment_image( 
                        get_post_thumbnail_id( $post->ID ), $imageDims )
                    //.$post->get_image()
                    .'<span class="item-title">'.$post->post_title
                    .'</a></span>'.$price.'<br/>'.$cart.'</li>';
        }
    }
    $item .= '</ul>';        
    return $item;
}

