            if($anItem['product_id'] != 2244)
            {
                $total_valid_items += $anItem['qty'];
            }
        }
        //$num_cart_items = $order->get_item_count();
        $type = $total_valid_items.'_game_purchase';
    
        //This will break if we add a 6 game reward tier
        if ($total_valid_items > 5){
                $type = '5_game_purchase';
        }
        //Now add any bucks not used when signing up for players club
        if(isset($_SESSION["cart_reward_bucks_left"])){
            $total_earned += $_SESSION["cart_reward_bucks_left"];
        }
        //echo 'type: '.$type;
        $result = $wpdb->get_row("SELECT * FROM {$wpdb->prefix}bg_bucks_rewards WHERE action_type = '$type' LIMIT 1");
        if($result){
            $total_earned += $result->buck_reward;
            return $total_earned;
        }
        return 'error';
    }
