    setcookie ('Remail', '', time() - 3600);
    setcookie ('RreviewText', '', time() - 3600);
    setcookie ('RstarRating', '', time() - 3600);
    unset($_COOKIE['RproductID']);
    unset($_COOKIE['Rauthor']);
    unset($_COOKIE['Remail']);
    unset($_COOKIE['RreviewText']);
    unset($_COOKIE['RstarRating']);
}

